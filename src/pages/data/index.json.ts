// Machine-readable index of everything published: /data/index.json
import type { APIRoute } from "astro";
import { answeringModel, editionNumber, editions, getForecast, kingSha, forecastSha } from "../../lib/editions";

const ORIGIN = "https://ifclaudewasking.com";

export const GET: APIRoute = () =>
  new Response(
    JSON.stringify(
      {
        name: "If Claude Was King",
        description: "Quarterly one-year plans written by the latest Claude model in answer to a fixed prompt, published unedited, with numeric forecasts scored against real figures.",
        disclaimer: "An independent experiment. Not affiliated with or endorsed by Anthropic. Generated by an AI model as a thought experiment. Not advice.",
        prompt_sha256: kingSha,
        forecast_prompt_sha256: forecastSha,
        schemas: { edition: `${ORIGIN}/schema/edition.schema.json`, forecast: `${ORIGIN}/schema/forecast.schema.json` },
        editions: editions.map((e) => ({
          number: editionNumber(e),
          date: e.edition_date,
          model: answeringModel(e),
          summary: e.content.summary,
          page: `${ORIGIN}/editions/${e.edition_date}`,
          markdown: `${ORIGIN}/editions/${e.edition_date}.md`,
          json: `${ORIGIN}/data/editions/${e.edition_date}.json`,
          transcript: `${ORIGIN}/raw/${e.edition_date}.json`,
          forecast: getForecast(e.edition_date) ? `${ORIGIN}/data/forecasts/${e.edition_date}.json` : null,
        })),
      },
      null,
      2,
    ),
    { headers: { "Content-Type": "application/json; charset=utf-8" } },
  );
